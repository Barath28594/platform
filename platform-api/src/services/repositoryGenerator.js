const {
    generatePipeline
} = require("../pipelines/pipelineGenerator");

function generateRepository(application, terraform) {

    return {

        ...terraform,

        ".github/workflows/terraform.yml":
            generatePipeline(application),

        ".gitignore":
            generateGitignore(),

        "README.md":
            generateReadme(application)

    };
}

function generateReadme(application) {

    return `# ${application.applicationName}

Generated by Velocity Platform.

## Application

${application.applicationName}

## Owner

${application.owner}

## Team

${application.team}

## Cloud

${application.cloud}

## Region

${application.region}

## Environment

${application.environment}

## Service

${application.service}

---

Infrastructure generated automatically by Velocity.
`;
}

function generateGitignore() {

    return `.terraform/
*.tfstate
*.tfstate.*
crash.log
terraform.tfvars
*.tfplan
`;

}

module.exports = {
    generateRepository
};